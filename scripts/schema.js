export function createIndexes(db, log = () => {}) {
  for (const [i, def] of INDEXES.entries()) {
    log(`index ${def}`);
    db.exec(`CREATE INDEX IF NOT EXISTS ix_${i} ON ${def}`);
  }
  db.exec('ANALYZE');
}
